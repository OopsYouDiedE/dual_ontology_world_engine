using System.Text;
using System.Text.Json;

namespace DuelView.Dv;

/// <summary>
/// Precompiles .dv AST into reflection-free static C# source code (.g.cs) or validates declaration schema.
/// </summary>
public static class DvCompiler
{
    public static string CompileToCSharp(DvDocument document, string namespaceName = "DuelView.Generated", string className = "CompiledDvContent")
    {
        ArgumentNullException.ThrowIfNull(document);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// Precompiled from DV declaration source; do not modify manually.");
        sb.AppendLine($"namespace {namespaceName};");
        sb.AppendLine();
        sb.AppendLine($"public static class {className}");
        sb.AppendLine("{");
        sb.AppendLine($"    public const string Schema = {JsonSerializer.Serialize(DvDocument.Schema)};");
        sb.AppendLine($"    public const string Hash = {JsonSerializer.Serialize(document.Hash)};");
        sb.AppendLine();
        sb.AppendLine("    public static readonly string RawJson = @\"");
        var rawJsonEscaped = document.Root.GetRawText().Replace("\"", "\"\"");
        sb.Append(rawJsonEscaped);
        sb.AppendLine("\";");
        sb.AppendLine("}");
        return sb.ToString();
    }

    public static DvDocument Compile(string source)
    {
        return DvDocument.Parse(source);
    }

    public static DvDocument CompileBundle(IEnumerable<string> sources)
    {
        return DvDocument.ParseBundle(sources);
    }
}
