using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using DualOntologyWorldEngine.Core;
using DualOntologyWorldEngine.Core.Mind;
using DualOntologyWorldEngine.Core.Timeline;

namespace DualOntologyWorldEngine.Simulation;

/// <summary>
/// 规范化轨迹记录项（Normalized Trajectory Entry）。
/// 严格记录离散行动值、因果顺序、审查、意图算子、事件产出与身心演化叙事。
/// </summary>
public sealed record TrajectoryEntry(
    double Time,
    long Sequence,
    string Actor,
    string Op,
    string? Target,
    string? Scene,
    bool Allowed,
    string Phase,
    string Outcome,
    string Details,
    string ActionLabel = "",
    string Narrative = "",
    string ActorRole = "");

/// <summary>
/// 规范化轨迹记录器。
/// 在时间线上捕获每一次行动结算，生成跨 Core 可验证、叙事清晰的规范化轨迹并支持导出。
/// </summary>
public sealed class TrajectoryRecorder
{
    private long _seqCounter = 0;
    public List<TrajectoryEntry> Entries { get; } = new();
    public Dictionary<int, List<string>> DailyNotes { get; } = new();

    public void AddDailyNote(int day, string note)
    {
        if (!DailyNotes.TryGetValue(day, out var list))
        {
            list = new List<string>();
            DailyNotes[day] = list;
        }
        list.Add(note);
    }

    public TrajectoryEntry Record(
        double time,
        Intent intent,
        ActionResolution resolution,
        string sceneName,
        string details = "",
        string narrative = "",
        string actionLabel = "",
        string actorRole = "")
    {
        var actorName = intent.Actor?.Name ?? "Unknown";
        var op = intent.Effect?.Op ?? "unknown";
        var targetName = (intent.Target as Entity)?.Name ?? intent.Target?.ToString();
        var allowed = resolution.Allowed;
        var phase = resolution.Event?.Get<string>("phase") ?? "Main";
        var outcome = resolution.Result?.Succeeded == true ? "Success" : (resolution.Reason ?? "Failed");
        var label = !string.IsNullOrWhiteSpace(actionLabel) ? actionLabel : (intent.Label ?? op);

        var entry = new TrajectoryEntry(
            Time: time,
            Sequence: ++_seqCounter,
            Actor: actorName,
            Op: op,
            Target: targetName,
            Scene: sceneName,
            Allowed: allowed,
            Phase: phase,
            Outcome: outcome,
            Details: details,
            ActionLabel: label,
            Narrative: narrative,
            ActorRole: actorRole
        );

        Entries.Add(entry);
        return entry;
    }

    /// <summary>
    /// 输出排版清晰、生动易读的 Markdown 规范化轨迹报告。
    /// 每条记录包含角色身份、具体行动、生动的现场经过与身心状态，条目间空一行。
    /// </summary>
    public string GenerateMarkdown()
    {
        var sb = new StringBuilder();
        sb.AppendLine("# 《异常感知学园》前五日规范化行动轨迹记录\n");
        sb.AppendLine("> **说明**：本文件由世界引擎运行时自动生成，完整记录前五日（共计 1000 AV 时间线）角色自发因果行动、现场情境、微观勘查、博弈交锋与模拟人生身心状态演化。\n");

        var groupedByDay = Entries.GroupBy(e => Math.Min(5, (int)(e.Time / 200.0) + 1));

        foreach (var group in groupedByDay)
        {
            sb.AppendLine($"## 第 {group.Key} 日行动轨迹 (基准时刻: {(group.Key - 1) * 200:F0} ~ {group.Key * 200:F0} AV)\n");

            foreach (var e in group)
            {
                var targetStr = string.IsNullOrEmpty(e.Target) ? "场景环境" : e.Target;
                var sceneStr = string.IsNullOrEmpty(e.Scene) ? "未知场景" : e.Scene;
                var statusStr = e.Allowed ? "通过" : "拒绝";
                var roleStr = string.IsNullOrEmpty(e.ActorRole) ? e.Actor : $"{e.Actor}（{e.ActorRole}）";
                var actionTitle = string.IsNullOrEmpty(e.ActionLabel) ? $"`{e.Op}`" : $"{e.ActionLabel} (`{e.Op}`)";

                sb.AppendLine($"【第 {e.Sequence} 步 | 时刻: {e.Time:F1} AV | 场景: {sceneStr}】");
                sb.AppendLine($"角色: {roleStr}");
                sb.AppendLine($"行动: {actionTitle} | 目标: {targetStr}");
                if (!string.IsNullOrWhiteSpace(e.Narrative))
                {
                    sb.AppendLine($"情境: {e.Narrative.Trim()}");
                }
                sb.AppendLine($"状态: {e.Details} | 审查: {statusStr}\n");
            }

            if (DailyNotes.TryGetValue(group.Key, out var notes) && notes.Count > 0)
            {
                sb.AppendLine($"### 🌙 第 {group.Key} 日夜晚作息与心智结算\n");
                foreach (var note in notes)
                {
                    sb.AppendLine(note);
                }
                sb.AppendLine();
            }
        }

        return sb.ToString();
    }

    /// <summary>
    /// 将轨迹记录持久化导出为 C# 强类型轨迹数据类代码（运行时生成 C#）。
    /// </summary>
    public string GenerateCSharpClass(string className = "FiveDaysRecordedTrajectory")
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// 本文件由世界引擎推演运行时动态生成。记录前五日全部规范化因果轨迹。");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine();
        sb.AppendLine("namespace DualOntologyWorldEngine.Simulation;");
        sb.AppendLine();
        sb.AppendLine($"public static class {className}");
        sb.AppendLine("{");
        sb.AppendLine("    public sealed record StepRecord(double Time, long Seq, string Actor, string Op, string? Target, string? Scene, bool Allowed, string Phase, string Outcome, string Details, string ActionLabel = \"\", string Narrative = \"\", string ActorRole = \"\");");
        sb.AppendLine();
        sb.AppendLine("    public static IReadOnlyList<StepRecord> Steps { get; } = new List<StepRecord>");
        sb.AppendLine("    {");

        foreach (var e in Entries)
        {
            var targetLiteral = e.Target == null ? "null" : $"\"{EscapeString(e.Target)}\"";
            var sceneLiteral = e.Scene == null ? "null" : $"\"{EscapeString(e.Scene)}\"";
            var detailsLiteral = $"\"{EscapeString(e.Details)}\"";
            var labelLiteral = $"\"{EscapeString(e.ActionLabel)}\"";
            var narrativeLiteral = $"\"{EscapeString(e.Narrative)}\"";
            var roleLiteral = $"\"{EscapeString(e.ActorRole)}\"";
            sb.AppendLine($"        new({e.Time:F1}, {e.Sequence}, \"{EscapeString(e.Actor)}\", \"{EscapeString(e.Op)}\", {targetLiteral}, {sceneLiteral}, {(e.Allowed ? "true" : "false")}, \"{EscapeString(e.Phase)}\", \"{EscapeString(e.Outcome)}\", {detailsLiteral}, {labelLiteral}, {narrativeLiteral}, {roleLiteral}),");
        }

        sb.AppendLine("    };");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private static string EscapeString(string str)
    {
        return str.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "").Replace("\n", " ");
    }
}
