using System.Reflection;
using System.Text.Json;
static List<object> Rec(params (string key, object value)[] fields) => fields.Select(f => (object)new List<object>{f.key,f.value}).ToList();
static List<object> Seq(params object[] items) => items.ToList();
static object Read(object value,string key) => ((List<object>)value).Cast<List<object>>().First(p=>(string)p[0]==key)[1];
var type=typeof(DvSession).Assembly.GetType("DVProgram")!;
object Call(string name,params object[] args)=>type.GetMethod(name,BindingFlags.Static|BindingFlags.NonPublic)!.Invoke(null,args)!;
void Require(bool value,string message) { if(!value) throw new Exception(message); }
string Json(object value)=>JsonSerializer.Serialize(value);
var reference=Rec(("type","ref"),("object","neutral"),("facet","state"),("field","done"));
var stop=Rec(("op","equals"),("ref",reference),("value",true));
var older=Rec(("kind","observation-batch"),("observations",Seq(Rec(("time",4d)))));
var received=Rec(("kind","observation-batch"),("observations",Seq(Rec(("time",17d)),Rec(("time",12d)))));
var unrelated=Rec(("kind","prediction"),("time",999d),("observations",Seq(Rec(("time",999d)))));
var mind=Rec(("domain","mind"),("subject","owner"),("time",10d),("history",Seq(older,received,unrelated)),
 ("objects",Rec(("neutral",Rec(("facets",Rec(("state",Rec(("done",Call("F_dv_field",false)))))))))));
var goal=Rec(("kind","evidence"),("minimum_time",0d),("refresh_until",stop));
var unmarked=Rec(("kind","evidence"),("minimum_time",1d));
var goals=Seq(goal,unmarked);
var beforeMind=Json(mind); var beforeGoals=Json(goals);
Require(Convert.ToDouble(Call("F_dvp_latest_received_time",mind))==17d,"Did not use latest actual received timestamp or read prediction timestamp");
var result=(List<object>)Call("F_dvp_refresh_current_evidence",Rec(("mind",mind)),goals);
Require(Convert.ToDouble(Read(result[0],"minimum_time"))==17d,"Unchanged mind.time hid later received information");
Require(Convert.ToDouble(Read(result[1],"minimum_time"))==1d,"Unmarked goal changed");
Require(Json(mind)==beforeMind && Json(goals)==beforeGoals,"Received clock changed knowledge or cached goals");
var done=Call("F_dv_store",mind,reference,Call("F_dv_field",true));
var settled=(List<object>)Call("F_dvp_refresh_current_evidence",Rec(("mind",done)),goals);
Require(Convert.ToDouble(Read(settled[0],"minimum_time"))==0d,"Known true stop predicate did not stop refresh");
Require(Convert.ToDouble(Call("F_dvp_latest_received_time",Rec(("time",10d))))==10d,"Empty history did not retain subject time");
var exact=new List<object>{new List<object>{"$dv_rational","35/2"}};
var parser=typeof(DvSession).GetMethod("ParseValue",BindingFlags.Static|BindingFlags.NonPublic)!;
var rational=parser.Invoke(null,new object[]{"{\"$dv_rational\":\"35/2\"}"})!;
var exactMind=Rec(("time",10d),("history",Seq(Rec(("kind","observation-batch"),("observations",Seq(Rec(("time",rational))))))));
Require(Call("F_dvp_latest_received_time",exactMind).ToString()=="35/2","Received timestamp lost exact fraction");
Console.WriteLine("Neutral received-time contract: later delivered observations advance marked freshness despite unchanged mind.time; prediction history ignored; cached goals and knowledge unchanged; known truth stops refresh; empty history retains time; exact fraction retained. No game session executed.");
