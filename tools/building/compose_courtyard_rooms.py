#!/usr/bin/env python3
"""Compose distinct courtyard rooms from the existing published component set.

This is a reusable asset-authoring command, never a gameplay or replay host.
The default writes candidates; --publish writes only this declaration's room
pairs after geometric preflight. It never changes existing models, components,
the campaign declaration, the presentation registry, or an asset bundle.
"""
from __future__ import annotations

import argparse
from collections import deque
from functools import lru_cache
import hashlib
import itertools
import json
import math
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_LAYOUT = ROOT / "tools/building/designs/courtyard_prototype_rooms.json"
MARKER = "# Generated by tools/building/compose_courtyard_rooms.py."


def resource(path: str) -> Path:
    if not path.startswith("res://"):
        raise ValueError(f"Published dependencies must use res://: {path}")
    result = (ROOT / path[6:]).resolve()
    if not result.is_relative_to(ROOT) or not result.is_file():
        raise ValueError(f"Missing or external dependency: {path}")
    return result


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def matrix(node: dict) -> list[list[float]]:
    if "matrix" in node:
        flat = node["matrix"]
        return [[flat[col * 4 + row] for col in range(4)] for row in range(4)]
    x, y, z, w = node.get("rotation", [0, 0, 0, 1])
    sx, sy, sz = node.get("scale", [1, 1, 1])
    tx, ty, tz = node.get("translation", [0, 0, 0])
    return [
        [(1-2*y*y-2*z*z)*sx, (2*x*y-2*z*w)*sy, (2*x*z+2*y*w)*sz, tx],
        [(2*x*y+2*z*w)*sx, (1-2*x*x-2*z*z)*sy, (2*y*z-2*x*w)*sz, ty],
        [(2*x*z-2*y*w)*sx, (2*y*z+2*x*w)*sy, (1-2*x*x-2*y*y)*sz, tz],
        [0, 0, 0, 1],
    ]


def multiply(a: list, b: list) -> list:
    return [[sum(a[row][k] * b[k][col] for k in range(4))
             for col in range(4)] for row in range(4)]


@lru_cache(maxsize=None)
def model_bounds(path: Path) -> tuple[list[float], list[float]]:
    data = path.read_bytes()
    if data[:4] != b"glTF":
        raise ValueError(f"Expected a published GLB: {path}")
    length, kind = struct.unpack_from("<II", data, 12)
    if kind != 0x4e4f534a:
        raise ValueError(f"Missing GLB JSON chunk: {path}")
    doc = json.loads(data[20:20+length])
    points = []

    def visit(index: int, parent: list) -> None:
        node = doc["nodes"][index]
        transform = multiply(parent, matrix(node))
        if "mesh" in node:
            for primitive in doc["meshes"][node["mesh"]]["primitives"]:
                accessor = doc["accessors"][primitive["attributes"]["POSITION"]]
                if "min" not in accessor or "max" not in accessor:
                    raise ValueError(f"Geometry has no declared bounds: {path}")
                for corner in itertools.product(*zip(accessor["min"], accessor["max"])):
                    points.append([sum(transform[row][j]*corner[j] for j in range(3))
                                   + transform[row][3] for row in range(3)])
        for child in node.get("children", []):
            visit(child, transform)

    for node in doc["scenes"][doc.get("scene", 0)]["nodes"]:
        visit(node, matrix({}))
    if not points:
        raise ValueError(f"Empty published geometry: {path}")
    return ([min(p[i] for p in points) for i in range(3)],
            [max(p[i] for p in points) for i in range(3)])


@lru_cache(maxsize=None)
def component(component_hash: str) -> dict:
    uri = f"res://assets/scenes/campaign_rooms/components/{component_hash}.tscn"
    path = resource(uri)
    text = path.read_text(encoding="utf-8")
    models = re.findall(r'path="(res://[^"\n]+\.glb)"', text)
    if len(models) != 1:
        raise ValueError(f"Expected one published model per prefab: {uri}")
    model = resource(models[0])
    script = resource(uri[:-5] + ".gd")
    low, high = model_bounds(model)
    slots = {}
    for name in ("Front", "Back"):
        match = re.search(r'\[node name="' + name + r'"[^\n]*\]\n(.*?)(?=\n\[|\Z)', text, re.S)
        if match:
            pose = re.search(r'transform = Transform3D\(([^)]+)\)', match[1])
            if pose:
                slots[name] = [float(v) for v in pose[1].split(",")][-3:]
    kind = re.search(r'^component_kind = "([^"]+)"', text, re.M)
    return {"resource": uri, "model": models[0], "script": "res://" + script.relative_to(ROOT).as_posix(),
            "kind": kind[1] if kind else "", "min": low, "max": high, "slots": slots,
            "component_sha256": sha(path), "model_sha256": sha(model), "script_sha256": sha(script)}


def position(point: list, item: dict) -> list[float]:
    angle = math.radians(item.get("yaw", 0))
    c, s = math.cos(angle), math.sin(angle)
    px, py, pz = item["position"]
    x, y, z = point
    return [px + c*x + s*z, py + y, pz - s*x + c*z]


def rect_for(item: dict, info: dict) -> list[float]:
    corners = [position(list(p), item) for p in itertools.product(*zip(info["min"], info["max"]))]
    return [min(p[0] for p in corners), min(p[2] for p in corners),
            max(p[0] for p in corners), max(p[2] for p in corners)]


def preflight(layout: dict, room: dict, items: list) -> dict:
    settings = layout["preflight"]
    radius = settings["actor_radius"] + settings["extra_clearance"]
    inset = layout["wall_inset"]
    area = [-layout["width"]/2 + inset, -layout["depth"] + inset,
             layout["width"]/2 - inset, -inset]
    obstacles, targets = [], [{"id": "spawn", "point": layout["spawn"]}]
    for item in items:
        info = component(layout["assets"][item["asset"]])
        if item.get("solid"):
            box = rect_for(item, info)
            if box[0] < area[0] or box[1] < area[1] or box[2] > area[2] or box[3] > area[3]:
                raise ValueError(f"{room['id']}: furniture crosses the inner wall: {item['id']}")
            obstacles.append({"id": item["id"], "bounds_xz": box})
        for slot in item.get("check_slots", []):
            if slot not in info["slots"]:
                raise ValueError(f"{item['id']}: missing authored slot {slot}")
            targets.append({"id": item["id"] + "/" + slot, "point": position(info["slots"][slot], item)})
    for a, b in itertools.combinations(obstacles, 2):
        p, q = a["bounds_xz"], b["bounds_xz"]
        if p[0] < q[2] and p[2] > q[0] and p[1] < q[3] and p[3] > q[1]:
            raise ValueError(f"{room['id']}: solid furniture overlaps: {a['id']} and {b['id']}")

    def clearance(x: float, z: float) -> float:
        result = min(x-area[0], area[2]-x, z-area[1], area[3]-z)
        for obstacle in obstacles:
            x0, z0, x1, z1 = obstacle["bounds_xz"]
            result = min(result, math.hypot(max(x0-x, 0, x-x1), max(z0-z, 0, z-z1)))
        return result

    step = settings["grid_step"]
    x0, z0 = area[0]+radius, area[1]+radius
    nx = math.floor((area[2]-radius-x0)/step)+1
    nz = math.floor((area[3]-radius-z0)/step)+1
    cells = {(x, z) for x in range(nx) for z in range(nz)
             if clearance(x0+x*step, z0+z*step) >= radius}
    sx, _, sz = layout["spawn"]
    start = (round((sx-x0)/step), round((sz-z0)/step))
    if start not in cells:
        raise ValueError(f"{room['id']}: spawn is not clear")
    distances, queue = {start: 0}, deque([start])
    while queue:
        x, z = queue.popleft()
        for neighbor in ((x+1,z), (x-1,z), (x,z+1), (x,z-1)):
            if neighbor in cells and neighbor not in distances:
                distances[neighbor] = distances[x, z]+1
                queue.append(neighbor)
    for target in targets:
        x, _, z = target["point"]
        cell = (round((x-x0)/step), round((z-z0)/step))
        target["center_clearance_m"] = round(clearance(x, z), 6)
        target["radius_with_margin_m"] = radius
        target["connected"] = cell in distances and clearance(x, z) >= radius
        if not target["connected"]:
            raise ValueError(f"{room['id']}: no clear path to {target['id']}: {target}")
        target["grid_path_m"] = round(distances[cell]*step, 4)
    return {"room": room["id"], "targets": targets, "solid_geometry": obstacles,
            "reachable_cells": len(distances), "walkable_cells": len(cells), "status": "passed"}


def format_value(value) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def scene_text(layout: dict, room: dict, items: list, script_uri: str, published: bool) -> str:
    used = list(dict.fromkeys(item["asset"] for item in items))
    ext = {asset: f"{index+2}_prefab" for index, asset in enumerate(used)}
    lines = [f'[gd_scene load_steps={len(used)+3} format=3]', "",
             f'[ext_resource type="Script" path="{script_uri}" id="1_script"]']
    for asset in used:
        uri = component(layout["assets"][asset])["resource"]
        lines.append(f'[ext_resource type="PackedScene" path="{uri}" id="{ext[asset]}"]')
    lines += [f'[ext_resource type="FontFile" path="{layout["font"]}" id="label_font"]', "",
              f'[node name="{room["id"]}" type="Node3D"]', 'script = ExtResource("1_script")',
              f'metadata/room_id = {format_value(room["id"])}', 'metadata/static_unit_baked = true',
              'metadata/candidate_only = ' + ('false' if published else 'true'), 'metadata/core_binding = "campaign.rooms"',
              'metadata/composition_source = "res://tools/building/designs/courtyard_prototype_rooms.json"',
              f'metadata/adaptation = {format_value(layout["adaptation"])}', "",
              '[node name="Instances" type="Node3D" parent="."]']
    for item in items:
        lines += ["", f'[node name="{item["id"]}" parent="Instances" instance=ExtResource("{ext[item["asset"]]}")]',
                  'position = Vector3(' + ', '.join(str(v) for v in item["position"]) + ')']
        if item.get("yaw"):
            lines.append(f'rotation = Vector3(0, {math.radians(item["yaw"]):.10g}, 0)')
        lines += [f'instance_id = {format_value(item["id"])}',
                  f'entity_id = {format_value(room["focus"] if item["id"] == room["primary_component"] else "")}',
                  f'portal_id = {format_value(item.get("portal", ""))}']
        if item.get("solid"):
            info = component(layout["assets"][item["asset"]])
            low, high = info["min"], info["max"]
            box = [{"name": "CompositionBody", "parent_node": "",
                    "position": [round((a+b)/2, 7) for a,b in zip(low,high)],
                    "size": [round(b-a, 7) for a,b in zip(low,high)]}]
            lines.append('collision_boxes_json = ' + format_value(format_value(box)))
            lines.append('static_collision = "none"')
    lines += ["", '[node name="RoomPlaque" type="Label3D" parent="."]',
              'position = Vector3(-0.25, 2.85, -6.49)', 'pixel_size = 0.005',
              'font = ExtResource("label_font")', 'font_size = 44', 'outline_size = 6',
              'modulate = Color(0.92, 0.88, 0.77, 1)', 'outline_modulate = Color(0.13, 0.11, 0.09, 1)',
              'text = ' + format_value(room["label"]), ""]
    return "\n".join(lines)


SCRIPT = MARKER + '''
# Presentation only: cognition, facts and actions remain authoritative in Core.
extends Node3D

func find_component(instance_id: String) -> Node3D:
    for component in $Instances.get_children():
        if component.get("instance_id") == instance_id:
            return component as Node3D
    return null
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--layout", type=Path, default=DEFAULT_LAYOUT)
    parser.add_argument("--candidate-root", type=Path, default=ROOT / ".runtime/courtyard-room-candidates")
    parser.add_argument("--publish", action="store_true", help="Publish only the validated new room pairs; keep all shared assets unchanged")
    args = parser.parse_args()
    layout = json.loads(args.layout.read_text(encoding="utf-8"))
    if layout["schema"] != "campaign-room-composition-v1":
        raise ValueError("Unsupported room composition schema")
    topology = json.loads(resource(layout["source_topology"]).read_text(encoding="utf-8"))
    topology_rooms = {r["id"]: r for r in topology["rooms"]}
    published = json.loads(resource(layout["source_publication"]).read_text(encoding="utf-8"))
    for component_hash in layout["assets"].values():
        if component_hash not in published["components"]:
            raise ValueError(f"Component is not in the existing publication: {component_hash}")
    resource(layout["font"])
    output = ROOT / "assets/scenes/campaign_rooms/rooms" if args.publish else args.candidate_root / "rooms"
    report_root = ROOT / "tools/building/candidates/courtyard_rooms" if args.publish else args.candidate_root
    report = {"schema": "campaign-room-authoring-report-v1", "mode": "published" if args.publish else "candidate",
              "scope": "Conservative 2D geometric connectivity using actual GLB mesh bounds and a 0.30 m expanded actor radius; actual Godot navigation and gameplay require the normal host.",
              "layout": "res://" + args.layout.resolve().relative_to(ROOT).as_posix(),
              "layout_sha256": sha(args.layout), "topology_sha256": sha(resource(layout["source_topology"])),
              "new_models": 0, "modified_shared_components": 0, "rooms": [], "outputs": {}}
    fragments = {"rooms": {}, "focus_bindings": {}}
    outputs = {}
    for room in layout["rooms"]:
        original = topology_rooms[room["id"]]
        expected_floor = "1F" if original["absolute_floor"] == 48 else "2F" if original["absolute_floor"] == 56.4 else None
        if room["floor"] != expected_floor:
            raise ValueError(f"{room['id']}: floor disagrees with authoritative topology")
        items = [dict(item) for item in layout["common_instances"] + room["instances"]]
        for item in items:
            for key in ("id", "portal"):
                if key in item:
                    item[key] = item[key].format(room=room["id"], code=room["id"].replace("-", ""))
        if len({item["id"] for item in items}) != len(items):
            raise ValueError(f"{room['id']}: duplicate component id")
        checked = preflight(layout, room, items)
        checked["topology"] = original
        checked["purpose"] = room["purpose"]
        report["rooms"].append(checked)
        folder = output / room["id"]
        script = folder / (room["id"] + ".gd")
        scene = folder / (room["id"] + ".tscn")
        if script.exists() and not script.read_text(encoding="utf-8").startswith(MARKER):
            raise ValueError(f"Refusing to overwrite a room not owned by this authoring command: {script}")
        script_uri = "res://" + script.relative_to(ROOT).as_posix()
        outputs[script], outputs[scene] = SCRIPT, scene_text(layout, room, items, script_uri, args.publish)
        bbox = original["bbox"]
        scene_uri = "res://assets/scenes/campaign_rooms/rooms/" + room["id"] + "/" + room["id"] + ".tscn"
        fragments["rooms"][room["id"]] = {
            "scene": scene_uri, "label": room["label"], "width": layout["width"], "depth": layout["depth"],
            "floor": room["floor"], "spawn": layout["spawn"],
            "topology_ref": "tools/building/designs/campus-r3.json#rooms[" + room["id"] + "]",
            "topology_floor": original["floor"], "topology_absolute_floor": original["absolute_floor"],
            "topology_bbox": bbox, "map_position": [(bbox[0]+bbox[2])/2, (bbox[1]+bbox[3])/2],
            "topology_note": "四院路线使用 R3 连廊；本室为保留用途与动线的原型适配。",
            "source_adaptation": layout["adaptation"], "source_composition": report["layout"]}
        fragments["focus_bindings"][room["focus"]] = {
            "label": room["focus_label"], "component": room["primary_component"], "slot": "Front"}
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        content = text.encode("utf-8")
        if not path.is_file() or path.read_bytes() != content:
            path.write_bytes(content)
        report["outputs"]["res://" + path.relative_to(ROOT).as_posix()] = {"sha256": sha(path), "bytes": path.stat().st_size}
    report["dependencies"] = {name: component(value) for name,value in layout["assets"].items()}
    report_root.mkdir(parents=True, exist_ok=True)
    for name, data in [("authoring-report.json", report), ("presentation-fragments.json", fragments)]:
        (report_root / name).write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"mode": report["mode"], "rooms": len(report["rooms"]), "new_models": 0,
                      "targets_checked": sum(len(r["targets"]) for r in report["rooms"]),
                      "report": str(report_root / "authoring-report.json"),
                      "presentation_fragments": str(report_root / "presentation-fragments.json")}, ensure_ascii=False))


if __name__ == "__main__":
    main()
